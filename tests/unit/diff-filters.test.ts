import { describe, expect, test } from "bun:test";
import type { DiffHunk } from "../../src/types/diff.ts";
import {
  countChangedLines,
  exceedsChangedLineLimit,
  exceedsFileSizeLimit,
  isGeneratedContent,
  isLockfile,
  selectSkipReason,
  type SkipDecisionInput,
} from "../../src/diff/filters.ts";

function line(
  kind: "add" | "del" | "ctx",
  oldLine: number | null,
  newLine: number | null,
  position: number,
): DiffHunk["lines"][number] {
  return { kind, oldLine, newLine, position, text: "x" };
}

function hunks(): DiffHunk[] {
  return [
    {
      oldStart: 1,
      oldLines: 3,
      newStart: 1,
      newLines: 3,
      lines: [line("ctx", 1, 1, 1), line("add", null, 2, 2), line("del", 2, null, 3)],
    },
  ];
}

function base(overrides: Partial<SkipDecisionInput> = {}): SkipDecisionInput {
  return {
    status: "modified",
    path: "src/app.ts",
    binary: false,
    ignorePaths: [],
    headBlobBytes: 100,
    headSample: "const x = 1;\n",
    changedLines: 10,
    maxFileSizeKb: 500,
    maxChangedLinesPerFile: 1500,
    ...overrides,
  };
}

describe("isLockfile", () => {
  test("recognizes known lockfiles at any depth", () => {
    for (const name of [
      "bun.lock",
      "bun.lockb",
      "package-lock.json",
      "npm-shrinkwrap.json",
      "yarn.lock",
      "pnpm-lock.yaml",
      "Cargo.lock",
      "Gemfile.lock",
      "Pipfile.lock",
      "poetry.lock",
      "uv.lock",
      "composer.lock",
      "go.sum",
      "Podfile.lock",
      "gradle.lockfile",
    ]) {
      expect(isLockfile(name)).toBe(true);
      expect(isLockfile(`nested/dir/${name}`)).toBe(true);
    }
  });

  test("rejects non-lockfiles", () => {
    for (const path of ["src/app.ts", "package.json", "yarn.lock.txt", "lockfile"]) {
      expect(isLockfile(path)).toBe(false);
    }
  });
});

describe("isGeneratedContent", () => {
  test("detects each marker case-insensitively", () => {
    for (const marker of [
      "// @generated",
      "// @GENERATED code",
      "/* DO NOT EDIT */",
      "// do not edit this file",
      "# GENERATED FILE",
      "// Code generated by tool. DO NOT EDIT.",
    ]) {
      expect(isGeneratedContent(`${marker}\nconst x = 1;\n`)).toBe(true);
    }
  });

  test("ignores clean content and empty input", () => {
    expect(isGeneratedContent("const x = 1;\n// nothing special here\n")).toBe(false);
    expect(isGeneratedContent("")).toBe(false);
  });

  test("inspects only the header window", () => {
    const lateMarker = `${"// clean\n".repeat(20)}// @generated\n`;
    expect(isGeneratedContent(lateMarker)).toBe(false);
    const earlyMarker = `// @generated\n${"// clean\n".repeat(20)}const x = 1;\n`;
    expect(isGeneratedContent(earlyMarker)).toBe(true);
    expect(isGeneratedContent(`${"x".repeat(8192)}@generated`)).toBe(false);
    expect(isGeneratedContent(`@generated${"x".repeat(8192)}`)).toBe(true);
  });
});

describe("size and changed-line limits", () => {
  test("file size boundary is strict greater-than", () => {
    expect(exceedsFileSizeLimit(500 * 1024, 500)).toBe(false);
    expect(exceedsFileSizeLimit(500 * 1024 + 1, 500)).toBe(true);
    expect(exceedsFileSizeLimit(0, 500)).toBe(false);
  });

  test("changed lines count additions plus deletions only", () => {
    expect(countChangedLines(hunks())).toBe(2);
    expect(countChangedLines([])).toBe(0);
  });

  test("changed-line boundary is strict greater-than", () => {
    expect(exceedsChangedLineLimit(hunks(), 2)).toBe(false);
    expect(exceedsChangedLineLimit(hunks(), 1)).toBe(true);
  });
});

describe("selectSkipReason", () => {
  test("clean file has no skip reason", () => {
    expect(selectSkipReason(base())).toBeUndefined();
  });

  test("deleted wins without needing a head blob", () => {
    expect(
      selectSkipReason(
        base({
          status: "deleted",
          binary: true,
          unsupportedMode: true,
          path: "yarn.lock",
          ignorePaths: ["**"],
          headBlobBytes: null,
          headSample: null,
          changedLines: 9999,
        }),
      ),
    ).toBe("deleted");
  });

  test("unsupported-mode beats binary, lockfile, ignored, too-large, and generated", () => {
    expect(
      selectSkipReason(
        base({
          unsupportedMode: true,
          binary: true,
          path: "yarn.lock",
          ignorePaths: ["**"],
          headBlobBytes: 500 * 1024 + 1,
          headSample: "// @generated\n",
          changedLines: 9999,
        }),
      ),
    ).toBe("unsupported-mode");
  });

  test("binary beats lockfile, ignored, too-large, and generated", () => {
    expect(
      selectSkipReason(
        base({
          binary: true,
          path: "yarn.lock",
          ignorePaths: ["**"],
          headBlobBytes: 500 * 1024 + 1,
          headSample: "// @generated\n",
          changedLines: 9999,
        }),
      ),
    ).toBe("binary");
  });

  test("lockfile beats ignored, too-large, and generated", () => {
    expect(
      selectSkipReason(
        base({
          path: "sub/dir/yarn.lock",
          ignorePaths: ["**"],
          headBlobBytes: 500 * 1024 + 1,
          headSample: "// @generated\n",
          changedLines: 9999,
        }),
      ),
    ).toBe("lockfile");
  });

  test("ignored beats too-large and generated", () => {
    expect(
      selectSkipReason(
        base({
          path: "dist/bundle.js",
          ignorePaths: ["dist/**"],
          headBlobBytes: 500 * 1024 + 1,
          headSample: "// @generated\n",
          changedLines: 9999,
        }),
      ),
    ).toBe("ignored");
  });

  test("minified bundles skip as ignored at root and at depth", () => {
    const ignorePaths = ["**/*.min.*"];
    for (const path of ["bundle.min.js", "app.min.css", "src/generated/bundle.min.js", "public/assets/app.min.css"]) {
      expect(selectSkipReason(base({ path, ignorePaths }))).toBe("ignored");
    }
    expect(selectSkipReason(base({ path: "src/app.js", ignorePaths }))).toBeUndefined();
    expect(selectSkipReason(base({ path: "src/minifier.js", ignorePaths }))).toBeUndefined();
  });

  test("too-large beats generated for both byte and line caps", () => {
    expect(selectSkipReason(base({ headBlobBytes: 500 * 1024 + 1, headSample: "// @generated\n" }))).toBe("too-large");
    expect(selectSkipReason(base({ changedLines: 1501, headSample: "// @generated\n" }))).toBe("too-large");
  });

  test("generated applies only with an inspectable head sample", () => {
    expect(selectSkipReason(base({ headSample: "// @generated\n" }))).toBe("generated");
    expect(selectSkipReason(base({ headSample: null }))).toBeUndefined();
  });

  test("missing blob size skips only the byte check", () => {
    expect(selectSkipReason(base({ headBlobBytes: null }))).toBeUndefined();
    expect(selectSkipReason(base({ headBlobBytes: null, changedLines: 1501 }))).toBe("too-large");
  });
});
